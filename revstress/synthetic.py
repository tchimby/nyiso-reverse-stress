"""SYNTHETIC daily panel for tests and demos only. NOT real market data; never report results from it.

Features: seasonal temperature and load, Henry Hub with winter premium, a gas -> price heat-rate
relation, convex load response, a few spike days and pocket-minus-reference congestion (PJM: Dominion-Western;
NYISO: N.Y.C.-WEST). market="NYISO" rescales load to about 30 GW and congestion to NYISO levels; PJM output is
unchanged. Internal column names are kept (wh_* = reference zone, dom_* = load pocket).
"""

from __future__ import annotations

import warnings

import numpy as np
import pandas as pd

from . import config
from .market import Market, get_market
from .panel import PANEL_COLUMNS, gas_price_usd

SYNTHETIC_WARNING: str = (
    "SYNTHETIC DATA: generated by revstress.synthetic for tests/demos only; "
    "it is not PJM data and no result computed from it is a real result."
)
SYNTHETIC_SOURCE_LABEL: str = "SYNTHETIC"

# Per-market scale: load = base + hdd*s_hdd + cdd*s_cdd + N(0, noise), floored; congestion = base + AR(1) sd + load term.
# PLACEHOLDER magnitudes chosen only so the NYISO panel looks like NYISO scale (NYCA peaks about 20-32 GW).
_SCALE: dict[str, dict[str, float]] = {
    "PJM": dict(base=115_000.0, hdd=650.0, cdd=900.0, noise=3_000.0, floor=80_000.0, cong=4.0, cong_sd=3.0, cong_load=0.0003, cong_jump=(20.0, 60.0)),
    "NYISO": dict(base=17_500.0, hdd=130.0, cdd=450.0, noise=1_000.0, floor=12_000.0, cong=12.0, cong_sd=6.0, cong_load=0.0015, cong_jump=(40.0, 120.0)),
}


def synthetic_warning(market: "str | Market | None" = None) -> str:
    """SYNTHETIC warning text for the market (PJM: SYNTHETIC_WARNING)."""
    m = get_market(config.MARKET if market is None else market)
    if m.name == "PJM":
        return SYNTHETIC_WARNING
    return (
        f"SYNTHETIC DATA: generated by revstress.synthetic for tests/demos only; "
        f"it is not {m.synthetic_label} data and no result computed from it is a real result."
    )


def _ar1(rng: np.random.Generator, n: int, phi: float, sd: float) -> np.ndarray:
    """AR(1) series with stationary sd = sd."""
    eps = rng.normal(0.0, sd * np.sqrt(1.0 - phi**2), n)
    out = np.empty(n)
    out[0] = rng.normal(0.0, sd)
    for i in range(1, n):
        out[i] = phi * out[i - 1] + eps[i]
    return out


def generate_synthetic_panel(
    seed: int,
    start: str = "2019-01-01",
    end: str = "2025-12-31",
    warn: bool = True,
    market: "str | Market | None" = None,
) -> pd.DataFrame:
    """Return a SYNTHETIC daily panel (see panel.PANEL_COLUMNS) plus column 'synthetic_source'.

    Prices $/MWh, load MW, gas $/MMBtu. Deterministic given seed. df.attrs['warning'] holds
    the market's synthetic warning (SYNTHETIC_WARNING for PJM). wh_on == rt_wh_on and wh_off == rt_wh_off (panel
    contract). market=None means the active market (config.MARKET); prices are clipped at that market's cap.
    """
    m = get_market(config.MARKET if market is None else market)
    sc = _SCALE[m.name]
    warning = synthetic_warning(m)
    if warn:
        warnings.warn(warning, UserWarning, stacklevel=2)
    rng = np.random.default_rng(seed)
    dates = pd.date_range(start, end, freq="D")
    n = len(dates)
    doy = dates.dayofyear.to_numpy()
    phase = 2.0 * np.pi * (doy - 20) / 365.25

    temp_f = 55.0 - 25.0 * np.cos(phase) + _ar1(rng, n, 0.7, 6.0)
    hdd = np.maximum(65.0 - temp_f, 0.0)
    cdd = np.maximum(temp_f - 65.0, 0.0)
    load = np.maximum(sc["base"] + sc["hdd"] * hdd + sc["cdd"] * cdd + rng.normal(0.0, sc["noise"], n), sc["floor"])

    winter_prem = 0.35 * np.cos(phase)
    hh = np.maximum(3.0 * np.exp(_ar1(rng, n, 0.98, 0.25) + winter_prem), 0.5)

    frame = pd.DataFrame({"date": dates, "hh_usd": hh})
    gas = gas_price_usd(frame)
    month_mean = pd.Series(load).groupby(dates.month).transform("mean").to_numpy()
    l = np.log(load / month_mean)

    resid = _ar1(rng, n, 0.6, 0.08)
    da_on = (9.0 * gas + 3.0) * np.exp(2.0 * l + 6.0 * l**2 + resid)
    da_off = 0.75 * da_on * np.exp(rng.normal(0.0, 0.05, n))

    spike_p = 1.0 / (1.0 + np.exp(-(-6.0 + 40.0 * np.maximum(l, 0.0))))
    spike = rng.random(n) < spike_p
    spike_mult = np.where(spike, rng.uniform(1.8, 4.0, n), 1.0)
    rt_on = da_on * np.exp(rng.normal(0.02, 0.08, n)) * spike_mult
    rt_off = da_off * np.exp(rng.normal(0.01, 0.05, n))
    da_on, da_off, rt_on, rt_off = (np.clip(x, 5.0, m.energy_cap_usd) for x in (da_on, da_off, rt_on, rt_off))

    cong = sc["cong"] + _ar1(rng, n, 0.8, sc["cong_sd"]) + sc["cong_load"] * (load - month_mean)
    cong_spike = rng.random(n) < 0.01
    cong = cong + np.where(cong_spike, rng.uniform(*sc["cong_jump"], n), 0.0)

    panel = pd.DataFrame(
        {
            "date": dates,
            "wh_on": rt_on,
            "wh_off": rt_off,
            "dom_on": rt_on + cong,
            "dom_off": rt_off + 0.5 * cong,
            "da_wh_off": da_off,
            "rt_wh_off": rt_off,
            "da_wh_on": da_on,
            "rt_wh_on": rt_on,
            "load_peak_mw": load,
            "hh_usd": hh,
            "hdd": hdd,
            "cdd": cdd,
        }
    )[list(PANEL_COLUMNS)]
    panel["synthetic_source"] = SYNTHETIC_SOURCE_LABEL
    panel.attrs["warning"] = warning
    return panel
